#!/usr/bin/env python3
"""E27 V2b tier summary (AB-T-0376): reads _out/heartmula-swift-<tier>-<a|b>/{manifest,scores,run}.jsonl (+ style_fit_v2b.jsonl),
prints per-draw and pooled rows, applies the rules pre-registered in WIP/heartmula-port/MEASUREMENTS.md §V2b, writes
_out/summary-v2b.md.  usage: summarize_tiers.py"""
import json, math, pathlib, statistics as st, sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import common as C

V0 = dict(per=0.165, per_en=0.107, per_zh=0.457, cat=1, pq=8.30, ce=7.76)
TIERS = ["bf16", "lm8", "lm4", "c16", "cfg3"]


def rows(path):
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()] if path.exists() else []


def load(tier, draw):
    d = C.OUT / f"heartmula-swift-{tier}-{draw}"
    man = {r["id"]: r for r in rows(d / "manifest.jsonl") if r.get("ok")}
    sc = {r["id"]: r for r in rows(d / "scores.jsonl")}
    run = rows(d / "run.jsonl")
    return man, sc, (run[-1] if run else {})


def agg(takes):
    """takes: list of (manifest row, score row)."""
    if not takes:
        return None
    m = lambda f: st.mean(f(t) for t in takes)
    en = [s["per"] for _, s in takes if s["lang"] == "en"]; zh = [s["per"] for _, s in takes if s["lang"] == "zh"]
    out = dict(n=len(takes), per=m(lambda t: t[1]["per"]), per_en=st.mean(en) if en else math.nan, per_zh=st.mean(zh) if zh else math.nan,
               cat=sum(1 for _, s in takes if s["per"] > 0.60), pq=m(lambda t: t[1]["aes"]["PQ"]), ce=m(lambda t: t[1]["aes"]["CE"]),
               cu=m(lambda t: t[1]["aes"]["CU"]), pc=m(lambda t: t[1]["aes"]["PC"]), dns=m(lambda t: t[1]["dnsmos"]["ovrl_mos"]),
               audio_s=m(lambda t: t[0]["audio_s"]), eos=sum(1 for mr, _ in takes if mr.get("ended_on_end_token")),
               gain_lt1=sum(1 for mr, _ in takes if mr.get("limiter_gain", 1) < 1))
    if "wall_s" in takes[0][0]:
        out.update(wall=m(lambda t: t[0]["wall_s"]), rtf=sum(t[0]["audio_s"] for t in takes) / sum(t[0]["wall_s"] for t in takes),
                   lmfps=sum(t[0]["frames"] for t in takes) / sum(t[0]["lm_s"] for t in takes),
                   dit_win=sum(t[0]["dit_s"] for t in takes) / sum(t[0]["dit_windows"] for t in takes), sq=m(lambda t: t[0]["sq_s"]))
    if "snr_vs_source_db" in takes[0][0]:
        snrs = [t[0]["snr_vs_source_db"] for t in takes]
        out.update(snr_mean=st.mean(snrs), snr_min=min(snrs), snr_max=max(snrs), decode_s=m(lambda t: t[0]["decode_s"]))
    return out


def main():
    res, runs, per_song = {}, {}, {}
    for t in TIERS:
        pooled = []
        for d in "ab":
            man, sc, run = load(t, d)
            takes = [(man[i], sc[i]) for i in man if i in sc]
            if takes:
                res[(t, d)] = agg(takes); runs[(t, d)] = run; pooled += takes
                for mr, s in takes:
                    per_song.setdefault(t, {})[(d, mr["id"])] = (mr, s)
        if pooled:
            res[(t, "pooled")] = agg(pooled)
    sf = rows(C.OUT / "style_fit_v2b.jsonl")
    clap = {}
    for r in sf:
        clap.setdefault(r["system"], []).append(r)

    L = ["# E27 V2b — tier summary (generated by harness/summarize_tiers.py)", ""]
    L.append("| tier | draw | n | PER (en / zh) | cat. | AES PQ / CE | CU / PC | DNS | eos | audio s | RTF | LM fr/s | DiT s/win | phys after load / peak GB | MLX peak GB | CLAP rank (top-1) |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    L.append(f"| V0 torch-MPS bf16 (AB-R-0628) | A | 12 | {V0['per']:.3f} ({V0['per_en']:.3f} / {V0['per_zh']:.3f}) | {V0['cat']} | {V0['pq']:.2f} / {V0['ce']:.2f} | 7.99 / 6.21 | 2.14 | 8/12 | 109.1 | 0.68 | 10.1 | 4.9 | 16.4 / 39.1 | — | 5.42 (2) |")
    for t in TIERS:
        for d in ("a", "b", "pooled"):
            r = res.get((t, d))
            if not r:
                continue
            run = runs.get((t, d), {})
            phys = f"{run['phys_after_load']/1e9:.2f} / {run['phys_process_peak']/1e9:.2f}" if run else "—"
            mlx = f"{run['mlx_peak']/1e9:.2f}" if run else "—"
            sp = f"{r['rtf']:.2f} | {r['lmfps']:.1f} | {r['dit_win']:.2f}" if "rtf" in r else (f"decode {r['decode_s']:.1f} s | — | — " if "decode_s" in r else "— | — | —")
            cl = clap.get(f"heartmula-swift-{t}-{d}")
            cls = f"{st.mean(x['clap_rank'] for x in cl):.2f} ({sum(x['clap_top1'] for x in cl)})" if cl else "—"
            L.append(f"| {t} | {d.upper() if d != 'pooled' else '**pooled**'} | {r['n']} | {r['per']:.3f} ({r['per_en']:.3f} / {r['per_zh']:.3f}) | {r['cat']} | "
                     f"{r['pq']:.2f} / {r['ce']:.2f} | {r['cu']:.2f} / {r['pc']:.2f} | {r['dns']:.2f} | {r['eos']}/{r['n']} | {r['audio_s']:.1f} | {sp} | {phys} | {mlx} | {cls} |")
    # c16 SNR
    for d in ("a", "b", "pooled"):
        r = res.get(("c16", d))
        if r and "snr_mean" in r:
            L.append(f"\nc16-{d}: waveform SNR vs the fp32 decode (same codes, same noise) mean {r['snr_mean']:.1f} dB, min {r['snr_min']:.1f}, max {r['snr_max']:.1f}")

    # rules
    def g(t, k, d="pooled"):
        return res[(t, d)][k] if (t, d) in res else math.nan
    verdict = {}
    if ("bf16", "pooled") in res:
        b = res[("bf16", "pooled")]
        catA = res.get(("bf16", "a"), {}).get("cat", 99); catB = res.get(("bf16", "b"), {}).get("cat", 99)
        verdict["B"] = (b["per"] <= 0.215 and b["per"] <= 0.35 and b["pq"] >= 8.00 and b["ce"] >= 7.46 and catA <= 2 and catB <= 2,
                        f"pooled PER {b['per']:.3f} (≤ 0.215); PQ {b['pq']:.2f} (≥ 8.00) CE {b['ce']:.2f} (≥ 7.46); cat A {catA} B {catB} (≤ 2 each)")
        for rule, t in (("Q8", "lm8"), ("Q4", "lm4")):
            if (t, "pooled") in res:
                q = res[(t, "pooled")]
                ok = q["per"] <= b["per"] + 0.05 and q["per"] <= 0.35 and q["pq"] >= b["pq"] - 0.3 and q["ce"] >= b["ce"] - 0.3 and q["cat"] <= b["cat"] + 2
                miss = q["per"] - (b["per"] + 0.05)
                verdict[rule] = (ok, f"pooled PER {q['per']:.3f} vs bf16 {b['per']:.3f} (Δ {q['per']-b['per']:+.3f}, ≤ +0.05){' — MARGINAL miss' if (not ok and 0 < miss <= 0.03) else ''}; "
                                     f"PQ {q['pq']:.2f} / CE {q['ce']:.2f} (≥ {b['pq']-0.3:.2f} / {b['ce']-0.3:.2f}); cat {q['cat']} (≤ {b['cat']+2}); "
                                     f"default bar Δ ≤ 0.03: {q['per'] - b['per'] <= 0.03}")
        if ("c16", "pooled") in res:
            c = res[("c16", "pooled")]
            verdict["C16"] = (c["per"] <= b["per"] + 0.02 and c["pq"] >= b["pq"] - 0.1 and c["ce"] >= b["ce"] - 0.1,
                              f"pooled PER {c['per']:.3f} vs {b['per']:.3f} (Δ {c['per']-b['per']:+.3f}, ≤ +0.02); PQ {c['pq']:.2f} / CE {c['ce']:.2f} (≥ {b['pq']-0.1:.2f} / {b['ce']-0.1:.2f}); SNR mean {c.get('snr_mean', math.nan):.1f} dB")
    L.append("\n## Rules (pre-registered)\n")
    for k, (ok, txt) in verdict.items():
        L.append(f"- **{k}** {'✅ PASS' if ok else '❌ FAIL'} — {txt}")
    L.append("\nNoise yardstick |PER_A − PER_B|: " + ", ".join(f"{t} {abs(g(t,'per','a')-g(t,'per','b')):.3f}" for t in TIERS if (t, 'a') in res and (t, 'b') in res))
    # end-token behaviour (disclosed observation, not a pre-registered rule): cap rate, paired end frames vs bf16, run-on check
    L.append("\n## End token vs the 120 s cap (observation — not in the pre-registered rule)\n")
    L.append("| tier | capped (of n) | paired frames vs bf16: mean Δ, tier capped & bf16 ended | transcript / lyric words: ended takes | capped takes | capped takes with ratio > 1.3 |")
    L.append("|---|---|---|---|---|---|")
    base = per_song.get("bf16", {})
    for t in ("bf16", "lm8", "lm4", "cfg3"):
        ps = per_song.get(t, {})
        if not ps:
            continue
        capped = [k for k, (mr, _) in ps.items() if not mr.get("ended_on_end_token")]
        deltas = [ps[k][0]["frames"] - base[k][0]["frames"] for k in ps if k in base]
        newcap = sum(1 for k in ps if k in base and not ps[k][0]["ended_on_end_token"] and base[k][0]["ended_on_end_token"])
        def ratio(sc):
            r = len(sc.get("ref_norm", "").split()); h = len(sc.get("hyp_norm", "").split())
            return h / r if r else float("nan")
        ended_r = [ratio(sc) for k, (mr, sc) in ps.items() if mr.get("ended_on_end_token") and sc.get("lang") == "en"]
        capped_r = [ratio(sc) for k, (mr, sc) in ps.items() if not mr.get("ended_on_end_token") and sc.get("lang") == "en"]
        L.append(f"| {t} | {len(capped)}/{len(ps)} | {st.mean(deltas) if deltas else 0:+.0f} frames; {newcap} | "
                 f"{st.mean(ended_r):.2f} (en, n={len(ended_r)}) | {(st.mean(capped_r) if capped_r else float('nan')):.2f} (en, n={len(capped_r)}) | "
                 f"{sum(1 for x in capped_r if x > 1.3)} |")
    # per song
    L.append("\n## Per song PER (A / B)\n")
    L.append("| id | " + " | ".join(TIERS) + " |"); L.append("|---|" + "---|" * len(TIERS))
    for p in C.prompts():
        cells = []
        for t in TIERS:
            a = per_song.get(t, {}).get(("a", p["id"])); b = per_song.get(t, {}).get(("b", p["id"]))
            cells.append(f"{a[1]['per']:.3f}" if a else "—" if not b else "—")
            if b:
                cells[-1] += f" / {b[1]['per']:.3f}"
        L.append(f"| {p['id']} | " + " | ".join(cells) + " |")
    txt = "\n".join(L) + "\n"
    (C.OUT / "summary-v2b.md").write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
